"""Generate the per-agent files from their single sources, and stamp VERSION into every manifest.

    python scripts/sync-agents.py           # write everything
    python scripts/sync-agents.py --check   # exit 1 if anything is out of date (CI)

Sources (hand-written):  AGENTS.md, commands/aria-*.md, VERSION
Generated (never edit):  .cursor/rules/aria.mdc, .windsurf/rules/aria.md, .clinerules/aria.md,
                         .kiro/steering/aria.md, .qoder/rules/aria.md, .opencode/command/aria-*.md
Stamped (version only):  .claude-plugin/plugin.json, .claude-plugin/marketplace.json, plugin.json,
                         .cursor-plugin/plugin.json, gemini-extension.json
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESCRIPTION = ("Aria: make finished videos with expressive voices from code (script, narration with emotion tags, "
               "word-timed captions, React/TypeScript scenes, GPU render, export check). Use for any video, short, "
               "narration, voiceover, captions or Aria project work.")
NOTE = "generated by scripts/sync-agents.py from {src}: edit {src}, then run the script"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:  # universal newlines: CRLF checkouts compare equal
        return f.read()


def rules(agents):
    """Rule/steering files: AGENTS.md plus each agent's own frontmatter."""
    body = agents.rstrip("\n") + "\n"
    desc = json.dumps(DESCRIPTION)  # quoted: the text has colons
    yaml_note = "# " + NOTE.format(src="AGENTS.md")
    html_note = "<!-- " + NOTE.format(src="AGENTS.md") + " -->"
    return {
        ".cursor/rules/aria.mdc": (f"---\n{yaml_note}\ndescription: {desc}\n"
                                   f"globs: \"**/edit.tsx,**/script.json\"\nalwaysApply: false\n---\n\n{body}"),
        ".windsurf/rules/aria.md": f"---\n{yaml_note}\ntrigger: model_decision\ndescription: {desc}\n---\n\n{body}",
        ".kiro/steering/aria.md": f"---\n{yaml_note}\ninclusion: always\n---\n\n{body}",
        ".clinerules/aria.md": f"{html_note}\n\n{body}",
        ".qoder/rules/aria.md": f"{html_note}\n\n{body}",
    }


def split_frontmatter(text):
    if not text.startswith("---\n"):
        return [], text
    end = text.index("\n---\n", 4)
    return text[4:end].split("\n"), text[end + 5:]


def opencode_commands():
    """OpenCode commands from commands/: keep `description`, drop Claude-only keys, body unchanged."""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "commands", "aria-*.md"))):
        name = os.path.basename(path)
        src = f"commands/{name}"
        fm, body = split_frontmatter(read(src))
        keep = [line for line in fm if line.startswith("description:")]
        out[f".opencode/command/{name}"] = "---\n# " + NOTE.format(src=src) + "\n" + "\n".join(keep) + "\n---\n" + body
    return out


def manifests(version):
    out = {}
    for rel in (".claude-plugin/plugin.json", ".claude-plugin/marketplace.json", "plugin.json",
                ".cursor-plugin/plugin.json", "gemini-extension.json"):
        data = json.loads(read(rel))
        if "plugins" in data:
            for p in data["plugins"]:
                p["version"] = version
        else:
            data["version"] = version
        out[rel] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    return out


def main():
    check = "--check" in sys.argv[1:]
    version = read("VERSION").strip()
    want = {**rules(read("AGENTS.md")), **opencode_commands(), **manifests(version)}
    # generated OpenCode commands whose source command is gone
    stale = [os.path.relpath(p, ROOT).replace(os.sep, "/")
             for p in glob.glob(os.path.join(ROOT, ".opencode", "command", "aria-*.md"))]
    stale = [p for p in stale if p not in want]

    changed = []
    for rel, text in want.items():
        path = os.path.join(ROOT, rel)
        have = read(rel) if os.path.exists(path) else None
        if have == text:
            continue
        changed.append(rel)
        if not check:
            os.makedirs(os.path.dirname(path) or ROOT, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    for rel in stale:
        changed.append(rel + " (stale)")
        if not check:
            os.remove(os.path.join(ROOT, rel))

    if check:
        if changed:
            print("out of date (run python scripts/sync-agents.py):\n  " + "\n  ".join(changed))
            sys.exit(1)
        print(f"sync-agents: {len(want)} files up to date (version {version})")
    else:
        print(f"sync-agents: version {version}, {len(changed)} file(s) written" +
              ("".join(f"\n  {c}" for c in changed)))


if __name__ == "__main__":
    main()
